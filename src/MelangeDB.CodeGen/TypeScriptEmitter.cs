using System.Text;

namespace MelangeDB.CodeGen;

/// <summary>
/// TypeScript bindings for <c>@melangedb/client</c>, from the same parsed manifest the C# emitter
/// reads, mirroring the C# API's shape: <c>conn.db.Table</c> with merged-cache events, typed
/// lookups and subscription helpers per primary-key, unique, and indexed column, one stub per
/// reducer and producer, and the schema hash. Generated code stays thin; the cache, the anchor
/// boundary, and resume live in the runtime package, as they do in <c>MelangeDB.Client</c>.
/// </summary>
internal static class TypeScriptEmitter
{
    /// <summary>The one file the bindings are written to.</summary>
    public const string FileName = "melange-bindings.ts";

    private const string Runtime = "@melangedb/client";

    public static string Emit(ClientSchemaModel schema)
    {
        var enums = schema.Enums.Items.ToDictionary(static e => e.Name, StringComparer.Ordinal);
        var types = schema.ResultTypes.Items.ToDictionary(static t => t.Name, StringComparer.Ordinal);
        var b = new StringBuilder();
        Line(b, "// <auto-generated/>");
        Line(b, $"// Generated by MelangeDB.CodeGen from melange-schema.json (module {schema.Module}). Changes will be overwritten.");
        Line(b, "// Regenerate with: melange generate --lang ts melange-schema.json -o <dir>");
        Line(b, "/* eslint-disable */");
        Line(b, "import {");
        Line(b, "  ColumnKind,");
        Line(b, "  Identity,");
        Line(b, "  MelangeClient,");
        Line(b, "  TableCache,");
        Line(b, "  TableCaches,");
        Line(b, "  TaggedReader,");
        Line(b, "  ProtocolError,");
        Line(b, "  arg,");
        Line(b, "  compareBytes,");
        Line(b, "  encodeArguments,");
        Line(b, "  encodeKey,");
        Line(b, "  trimDefaults,");
        Line(b, "  type Arg,");
        Line(b, "  type ColumnValue,");
        Line(b, "  type Parameters,");
        Line(b, "  type ScheduleAt,");
        Line(b, "  type TableCodec,");
        Line(b, "  type TypedSubscription,");
        Line(b, $"}} from {Quote(Runtime)};");
        Line(b);
        Line(b, "/** The schema these bindings were generated from: compare it to the server's to see drift. */");
        Line(b, $"export const schemaHash = {Quote(schema.SchemaHash)};");
        Line(b, $"export const moduleName = {Quote(schema.Module)};");

        foreach (var e in schema.Enums.Items)
            EmitEnum(b, e);
        foreach (var table in schema.Tables.Items)
            EmitTable(b, table);
        foreach (var type in schema.ResultTypes.Items)
            EmitResultType(b, type, enums, types);

        EmitDbView(b, schema);
        EmitReducers(b, schema);
        if (schema.Producers.Length > 0)
            EmitProducers(b, schema, enums, types);
        EmitConnection(b, schema);

        // Silences "declared but never used" for imports a given schema does not need.
        Line(b);
        Line(b, "void [Identity, ProtocolError, TaggedReader, arg, compareBytes, encodeArguments, encodeKey, trimDefaults];");
        Line(b, "export type { Arg, ColumnValue, ScheduleAt };");
        return b.ToString();
    }

    private static void EmitEnum(StringBuilder b, ClientEnumModel e)
    {
        Line(b);
        Line(b, $"export const {e.Name} = {{");
        foreach (var member in e.Members.Items)
            Line(b, $"  {member.Name}: {EnumValue(e.Underlying, member.Value)},");
        Line(b, "} as const;");
        Line(b, $"export type {e.Name} = (typeof {e.Name})[keyof typeof {e.Name}];");
    }

    private static string EnumValue(WireKind underlying, string value) =>
        underlying is WireKind.Int64 or WireKind.UInt64 ? $"{value}n" : value;

    private static void EmitTable(StringBuilder b, ClientTableModel table)
    {
        var name = table.TypeName;
        Line(b);
        Line(b, $"/** One row of table '{table.TableName}', as the wire carries it to clients. */");
        Line(b, $"export interface {name} {{");
        foreach (var column in table.Columns.Items)
            Line(b, $"  {column.Name}: {ColumnType(column.Kind, column.EnumName)};");
        Line(b, "}");
        Line(b);
        Line(b, $"export const {name}Codec: TableCodec<{name}> = {{");
        Line(b, $"  tableName: {Quote(table.TableName)},");
        Line(b, "  columns: [");
        foreach (var column in table.Columns.Items)
            Line(b, $"    [{Quote(column.Name)}, ColumnKind.{column.Kind}],");
        Line(b, "  ],");
        Line(b, "  create: (values: Readonly<Record<string, ColumnValue>>) => ({");
        foreach (var column in table.Columns.Items)
            Line(b, $"    {column.Name}: values[{Quote(column.Name)}] as {ColumnType(column.Kind, column.EnumName)},");
        Line(b, "  }),");
        Line(b, $"  encodeKey: (row: {name}) => encodeKey(ColumnKind.{table.PrimaryKey.Kind}, row.{table.PrimaryKey.Name}),");
        Line(b, "};");
        Line(b);
        Line(b, $"/** Typed access to the '{table.TableName}' merged cache: rows, events, lookups, subscriptions. */");
        Line(b, $"export class {name}Table {{");
        Line(b, $"  readonly cache: TableCache<{name}>;");
        foreach (var column in table.Columns.Items.Where(static c => c.HasAccessor))
            Line(b, $"  readonly {column.Name}: {name}{column.Name}Accessor;");
        Line(b);
        Line(b, "  constructor(private readonly caches: TableCaches) {");
        Line(b, $"    this.cache = caches.getOrAdd({name}Codec);");
        foreach (var column in table.Columns.Items.Where(static c => c.HasAccessor))
            Line(b, $"    this.{column.Name} = new {name}{column.Name}Accessor(caches, this.cache);");
        Line(b, "  }");
        Line(b);
        Line(b, "  /** Rows the client's subscriptions cover, not the table's. */");
        Line(b, "  get count(): number {");
        Line(b, "    return this.cache.count;");
        Line(b, "  }");
        Line(b);
        Line(b, $"  rows(): {name}[] {{");
        Line(b, "    return this.cache.rows();");
        Line(b, "  }");
        Line(b);
        Line(b, $"  onInsert(listener: (row: {name}) => void): () => void {{");
        Line(b, "    return this.cache.onInsert(listener);");
        Line(b, "  }");
        Line(b);
        Line(b, $"  onUpdate(listener: (previous: {name}, current: {name}) => void): () => void {{");
        Line(b, "    return this.cache.onUpdate(listener);");
        Line(b, "  }");
        Line(b);
        Line(b, $"  onDelete(listener: (row: {name}) => void): () => void {{");
        Line(b, "    return this.cache.onDelete(listener);");
        Line(b, "  }");
        Line(b);
        Line(b, $"  subscribeAll(): Promise<TypedSubscription<{name}>> {{");
        Line(b, $"    return this.caches.subscribe({name}Codec, {Quote($"SELECT * FROM {table.TableName}")});");
        Line(b, "  }");
        Line(b, "}");

        foreach (var column in table.Columns.Items.Where(static c => c.HasAccessor))
            EmitAccessor(b, table, column);
    }

    private static void EmitAccessor(StringBuilder b, ClientTableModel table, ClientColumnModel column)
    {
        var name = table.TypeName;
        var type = ColumnType(column.Kind, column.EnumName);
        var key = $"ColumnKind.{column.Kind}";
        Line(b);
        Line(b, $"export class {name}{column.Name}Accessor {{");
        Line(b, $"  constructor(private readonly caches: TableCaches, private readonly cache: TableCache<{name}>) {{}}");
        if (column.IsPrimaryKey)
        {
            Line(b);
            Line(b, "  /** The cached row with this primary key, found by encoded key. */");
            Line(b, $"  find(value: {type}): {name} | undefined {{");
            Line(b, $"    return this.cache.findByKey(encodeKey({key}, value));");
            Line(b, "  }");
        }
        else
        {
            Line(b);
            Line(b, "  /** Cached rows whose value is in [low, high] (one value when high is left off), by key order. */");
            Line(b, $"  filter(low: {type}, high: {type} = low): {name}[] {{");
            Line(b, $"    const lowKey = encodeKey({key}, low);");
            Line(b, $"    const highKey = encodeKey({key}, high);");
            Line(b, "    return this.cache.rows().filter((row) => {");
            Line(b, $"      const candidate = encodeKey({key}, row.{column.Name});");
            Line(b, "      return compareBytes(candidate, lowKey) >= 0 && compareBytes(candidate, highKey) <= 0;");
            Line(b, "    });");
            Line(b, "  }");
        }

        var query = $"SELECT * FROM {table.TableName} WHERE {column.Name}";
        Line(b);
        Line(b, $"  subscribe(value: {type}): Promise<TypedSubscription<{name}>> {{");
        Line(b, $"    return this.caches.subscribe({name}Codec, {Quote(query + " = :p")}, {{ p: value as Parameters[string] }});");
        Line(b, "  }");
        Line(b);
        Line(b, $"  rescope(subscription: TypedSubscription<{name}>, value: {type}): Promise<void> {{");
        Line(b, "    return subscription.rescope({ p: value as Parameters[string] });");
        Line(b, "  }");
        Line(b);
        Line(b, $"  subscribeRange(low: {type}, high: {type}): Promise<TypedSubscription<{name}>> {{");
        Line(b, $"    return this.caches.subscribe({name}Codec, {Quote(query + " BETWEEN :lo AND :hi")}, {{ lo: low as Parameters[string], hi: high as Parameters[string] }});");
        Line(b, "  }");
        Line(b);
        Line(b, $"  rescopeRange(subscription: TypedSubscription<{name}>, low: {type}, high: {type}): Promise<void> {{");
        Line(b, "    return subscription.rescope({ lo: low as Parameters[string], hi: high as Parameters[string] });");
        Line(b, "  }");
        Line(b, "}");
    }

    private static void EmitResultType(StringBuilder b, ClientResultTypeModel type, Dictionary<string, ClientEnumModel> enums, Dictionary<string, ClientResultTypeModel> types)
    {
        Line(b);
        Line(b, $"/** A producer result record. Fields are positional on the wire, in this order. */");
        Line(b, $"export interface {type.Name} {{");
        foreach (var field in type.Fields.Items)
            Line(b, $"  {field.Name}: {ReferenceType(field.Type, enums, types)};");
        Line(b, "}");
        Line(b);
        Line(b, $"function read{type.Name}(reader: TaggedReader): {type.Name} {{");
        Line(b, "  const count = reader.array();");
        Line(b, $"  if (count < {type.Fields.Length}) throw new ProtocolError(`A {type.Name} carries {type.Fields.Length} fields, not ${{count}}.`);");
        Line(b, $"  const value: {type.Name} = {{");
        foreach (var field in type.Fields.Items)
            Line(b, $"    {field.Name}: {ReadExpression(field.Type, enums, types)},");
        Line(b, "  };");
        Line(b, $"  // Fields appended on the server after these bindings were generated are read past.");
        Line(b, $"  for (let extra = {type.Fields.Length}; extra < count; extra++) reader.skip();");
        Line(b, "  return value;");
        Line(b, "}");
    }

    private static void EmitDbView(StringBuilder b, ClientSchemaModel schema)
    {
        Line(b);
        Line(b, "/** Every public table's typed cache handle. */");
        Line(b, "export class MelangeDbView {");
        foreach (var table in schema.Tables.Items)
            Line(b, $"  readonly {table.TypeName}: {table.TypeName}Table;");
        Line(b);
        Line(b, "  constructor(readonly caches: TableCaches) {");
        foreach (var table in schema.Tables.Items)
            Line(b, $"    this.{table.TypeName} = new {table.TypeName}Table(caches);");
        Line(b, "  }");
        Line(b, "}");
    }

    private static void EmitReducers(StringBuilder b, ClientSchemaModel schema)
    {
        Line(b);
        Line(b, "/** One typed stub per client-callable reducer; each resolves to the commit's LSN. */");
        Line(b, "export class MelangeReducers {");
        Line(b, "  constructor(private readonly client: MelangeClient) {}");
        foreach (var reducer in schema.Reducers.Items)
        {
            Line(b);
            Line(b, $"  {Camel(reducer.Name)}({Parameters(reducer.Parameters.Items)}): Promise<bigint> {{");
            Line(b, $"    return this.client.callReducer({Quote(reducer.Name)}, encodeArguments({ArgumentList(reducer.Parameters.Items, schema)}));");
            Line(b, "  }");
        }

        Line(b, "}");
    }

    private static void EmitProducers(StringBuilder b, ClientSchemaModel schema, Dictionary<string, ClientEnumModel> enums, Dictionary<string, ClientResultTypeModel> types)
    {
        Line(b);
        Line(b, "/** One typed stub per producer: a read-only server call answered with a value (protocol 3). */");
        Line(b, "export class MelangeProducers {");
        Line(b, "  constructor(private readonly client: MelangeClient) {}");
        foreach (var producer in schema.Producers.Items)
        {
            Line(b);
            Line(b, $"  async {Camel(producer.Name)}({Parameters(producer.Parameters.Items)}): Promise<{ReferenceType(producer.Returns, enums, types)}> {{");
            Line(b, $"    const reply = await this.client.callProducer({Quote(producer.Name)}, encodeArguments({ArgumentList(producer.Parameters.Items, schema)}));");
            Line(b, "    const reader = new TaggedReader(reply.payload);");
            Line(b, $"    const value = {ReadExpression(producer.Returns, enums, types)};");
            Line(b, $"    if (!reader.end) throw new ProtocolError({Quote($"The {producer.Name} result left bytes unread.")});");
            Line(b, "    return value;");
            Line(b, "  }");
        }

        Line(b, "}");
    }

    private static void EmitConnection(StringBuilder b, ClientSchemaModel schema)
    {
        Line(b);
        Line(b, "/** A connected client with this schema's typed tables, reducers, and producers. */");
        Line(b, "export class MelangeConnection {");
        Line(b, "  static readonly schemaHash = schemaHash;");
        Line(b, "  readonly db: MelangeDbView;");
        Line(b, "  readonly reducers: MelangeReducers;");
        if (schema.Producers.Length > 0)
            Line(b, "  readonly producers: MelangeProducers;");
        Line(b);
        Line(b, "  constructor(readonly client: MelangeClient) {");
        Line(b, "    this.db = new MelangeDbView(new TableCaches(client));");
        Line(b, "    this.reducers = new MelangeReducers(client);");
        if (schema.Producers.Length > 0)
            Line(b, "    this.producers = new MelangeProducers(client);");
        Line(b, "  }");
        Line(b);
        Line(b, "  /** Who the server says this connection is. Read it; never derive it. */");
        Line(b, "  get identity(): Identity | null {");
        Line(b, "    return this.client.identity;");
        Line(b, "  }");
        Line(b, "}");
    }

    /// <summary>A parameter list; trailing parameters with a default are optional, and the server fills them.</summary>
    private static string Parameters(IReadOnlyList<ClientParameterModel> parameters)
    {
        var optionalFrom = parameters.Count;
        while (optionalFrom > 0 && parameters[optionalFrom - 1].Default is not null)
            optionalFrom--;
        return string.Join(", ", parameters.Select((p, i) =>
            $"{ParameterName(p.Name)}{(i >= optionalFrom ? "?" : "")}: {ParameterType(p)}"));
    }

    /// <summary>
    /// The argument array. Defaulted trailing parameters left undefined are dropped from the end, so
    /// the server applies its own defaults (C9.2).
    /// </summary>
    private static string ArgumentList(IReadOnlyList<ClientParameterModel> parameters, ClientSchemaModel schema)
    {
        if (parameters.Count == 0)
            return "[]";
        var required = parameters.Count;
        while (required > 0 && parameters[required - 1].Default is not null)
            required--;
        var args = string.Join(", ", parameters.Select(p => ArgExpression(p, ParameterName(p.Name), schema)));
        if (required == parameters.Count)
            return $"[{args}]";
        var optional = string.Join(", ", parameters.Skip(required).Select(p => ParameterName(p.Name)));
        return $"trimDefaults([{args}], [{optional}], {required})";
    }

    private static string ArgExpression(ClientParameterModel p, string name, ClientSchemaModel schema)
    {
        // A defaulted parameter left undefined but followed by one that is given takes its
        // manifest default here; trailing ones are dropped instead, and the server fills them.
        var value = p.Default is null ? name : $"({name} === undefined ? {DefaultLiteral(p, schema)} : {name})";
        if (p.IsArray)
            return $"arg.optional({value}, (items) => arg.array(items.map((v) => {ScalarArg(p.Kind, p.EnumName, "v", schema)})))";
        return p.Kind is WireKind.String or WireKind.Bytes
            ? $"arg.optional({value}, (v) => {ScalarArg(p.Kind, p.EnumName, "v", schema)})"
            : ScalarArg(p.Kind, p.EnumName, value, schema);
    }

    /// <summary>The manifest's default literal text (<c>1</c>, <c>true</c>, <c>"abc"</c>, <c>null</c>) as a TypeScript value.</summary>
    private static string DefaultLiteral(ClientParameterModel p, ClientSchemaModel schema)
    {
        var text = p.Default!;
        if (text == "null")
            return "null";
        var kind = p.EnumName is null ? p.Kind : schema.Enums.Items.First(e => e.Name == p.EnumName).Underlying;
        return kind is WireKind.Int64 or WireKind.UInt64 or WireKind.Timestamp ? text + "n" : text;
    }

    private static string ScalarArg(WireKind kind, string? enumName, string value, ClientSchemaModel schema)
    {
        if (enumName is not null)
        {
            var underlying = schema.Enums.Items.First(e => e.Name == enumName).Underlying;
            return underlying == WireKind.UInt64 ? $"arg.uint64({value})" : $"arg.int64({value})";
        }

        return kind switch
        {
            WireKind.Bool => $"arg.bool({value})",
            WireKind.Int8 or WireKind.Int16 or WireKind.Int32 or WireKind.Int64 => $"arg.int64({value})",
            WireKind.UInt8 or WireKind.UInt16 or WireKind.UInt32 or WireKind.UInt64 => $"arg.uint64({value})",
            WireKind.Float32 or WireKind.Float64 => $"arg.float64({value})",
            WireKind.String => $"arg.string({value})",
            WireKind.Bytes => $"arg.bytes({value})",
            WireKind.Identity => $"arg.identity({value})",
            WireKind.Timestamp => $"arg.timestamp({value})",
            _ => throw new InvalidOperationException($"Parameter kind {kind} has no argument encoding."),
        };
    }

    private static string ParameterType(ClientParameterModel p)
    {
        var element = ColumnType(p.Kind, p.EnumName);
        return p.IsArray ? $"readonly {Parenthesize(element)}[]" : element;
    }

    /// <summary>The TypeScript type of a column or parameter kind (CLIENT-BINDINGS.md, TypeScript).</summary>
    private static string ColumnType(WireKind kind, string? enumName) => enumName ?? kind switch
    {
        WireKind.Bool => "boolean",
        WireKind.Int64 or WireKind.UInt64 or WireKind.Timestamp => "bigint",
        WireKind.String => "string | null",
        WireKind.Bytes => "Uint8Array | null",
        WireKind.Identity => "Identity",
        WireKind.ScheduleAt => "ScheduleAt",
        _ => "number",
    };

    /// <summary>The TypeScript type of a manifest type reference (scalar, enum, or record; <c>?</c> and <c>[]</c> suffixes).</summary>
    private static string ReferenceType(string reference, Dictionary<string, ClientEnumModel> enums, Dictionary<string, ClientResultTypeModel> types)
    {
        if (reference.EndsWith("[]", StringComparison.Ordinal))
            return $"{Parenthesize(ReferenceType(reference.Substring(0, reference.Length - 2), enums, types))}[] | null";
        if (reference.EndsWith("?", StringComparison.Ordinal))
            return $"{ReferenceType(reference.Substring(0, reference.Length - 1), enums, types)} | null";
        if (enums.ContainsKey(reference))
            return reference;
        if (types.TryGetValue(reference, out var record))
            return record.IsValueType ? reference : $"{reference} | null";
        return ColumnType(ResultTypeReference.ScalarKind(reference) ?? throw new InvalidOperationException($"Unknown type reference '{reference}'."), null);
    }

    /// <summary>The expression that reads a type reference from <c>reader</c>, positionally.</summary>
    private static string ReadExpression(string reference, Dictionary<string, ClientEnumModel> enums, Dictionary<string, ClientResultTypeModel> types)
    {
        if (reference.EndsWith("[]", StringComparison.Ordinal))
        {
            var element = reference.Substring(0, reference.Length - 2);
            return $"(reader.tryNull() ? null : Array.from({{ length: reader.array() }}, () => {ReadExpression(element, enums, types)}))";
        }

        if (reference.EndsWith("?", StringComparison.Ordinal))
            return $"(reader.tryNull() ? null : {ReadExpression(reference.Substring(0, reference.Length - 1), enums, types)})";
        if (enums.TryGetValue(reference, out var e))
            return e.Underlying is WireKind.Int64 or WireKind.UInt64 ? $"(reader.int() as {reference})" : $"(Number(reader.int()) as {reference})";
        if (types.TryGetValue(reference, out var record))
            return record.IsValueType ? $"read{reference}(reader)" : $"(reader.tryNull() ? null : read{reference}(reader))";
        return (ResultTypeReference.ScalarKind(reference) ?? throw new InvalidOperationException($"Unknown type reference '{reference}'.")) switch
        {
            WireKind.Bool => "reader.bool()",
            WireKind.Int64 or WireKind.UInt64 => "reader.int()",
            WireKind.Float32 or WireKind.Float64 => "reader.float()",
            WireKind.String => "(reader.tryNull() ? null : reader.string())",
            WireKind.Bytes => "(reader.tryNull() ? null : reader.bytesValue())",
            WireKind.Identity => "reader.identity()",
            WireKind.Timestamp => "reader.timestamp()",
            _ => "Number(reader.int())",
        };
    }

    private static string Parenthesize(string type) => type.Contains(" ") ? $"({type})" : type;

    private static string Camel(string name) => name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

    private static readonly HashSet<string> Reserved = new(StringComparer.Ordinal)
    {
        "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
        "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
        "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
        "let", "static", "implements", "interface", "package", "private", "protected", "public", "await", "arguments", "eval",
    };

    private static string ParameterName(string name) => Reserved.Contains(name) ? name + "_" : name;

    private static string Quote(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ when c < ' ' => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }

        return builder.Append('"').ToString();
    }

    private static void Line(StringBuilder builder, string text = "") => builder.Append(text).Append('\n');
}

using System.Net.WebSockets;
using System.Text.Json;
using System.Text.Json.Nodes;
using MelangeDB.Protocol;

namespace MelangeDB.Conformance;

/// <summary>
/// Records the decode corpus: scripted sessions against a live <see cref="ConformanceServer"/>
/// over a raw socket, capturing every server-to-client frame's exact bytes beside its canonical
/// decode (<see cref="CorpusJson"/>). A client in another language replays each session's frames
/// through its own decoder and must reproduce every <c>expect</c> exactly.
/// <para>
/// The output is deterministic, which is what lets a test hold the committed corpus to the
/// server: a fresh data directory, a manual clock, one scripted order, frames within a step
/// ordered by channel (the only ordering the protocol promises), and the two per-run random ids in
/// <c>Welcome</c> rewritten to fixed values — the only bytes in the corpus that are not exactly as
/// the server sent them, and documented as such.
/// </para>
/// </summary>
public static class CorpusRecorder
{
    /// <summary>The corpus format; bumped only when the corpus's own JSON shape changes.</summary>
    public const int Format = 1;

    /// <summary>What every corpus <c>Welcome</c> carries in place of the per-run connection id.</summary>
    public static readonly Guid FixedConnectionId = new("00000000-0000-0000-0000-00000000c0de");

    /// <summary>What every corpus <c>Welcome</c> carries in place of the per-run log epoch.</summary>
    public static readonly Guid FixedEpochId = new("00000000-0000-0000-0000-0000000e70c4");

    private static readonly MessagePackFrameSerializer Serializer = new();

    private static readonly TimeSpan StepTimeout = TimeSpan.FromSeconds(20);

    public static async Task<JsonObject> RecordAsync(CancellationToken cancellationToken = default)
    {
        await using var server = await ConformanceServer.StartAsync(null, cancellationToken).ConfigureAwait(false);
        var sessions = new JsonArray
        {
            await HandshakeAndInitialSetAsync(server, cancellationToken).ConfigureAwait(false),
            await DeltasAsync(server, cancellationToken).ConfigureAwait(false),
            await CallFailuresAsync(server, cancellationToken).ConfigureAwait(false),
            await ColumnMasksAsync(server, cancellationToken).ConfigureAwait(false),
            await ProducersAsync(server, cancellationToken).ConfigureAwait(false),
            await HeartbeatAsync(server, cancellationToken).ConfigureAwait(false),
        };
        foreach (var session in await ResumeAsync(server, cancellationToken).ConfigureAwait(false))
            sessions.Add(session);
        sessions.Add(await ReauthenticateAsync(server, cancellationToken).ConfigureAwait(false));

        return new JsonObject
        {
            ["format"] = Format,
            ["protocolVersion"] = MessagePackFrameSerializer.ProtocolVersion,
            ["about"] = "The MelangeDB client decode corpus. Generated by tools/MelangeDB.Conformance (`record`); do not edit by hand. See docs/CLIENT-CONFORMANCE.md.",
            ["normalized"] = new JsonArray("Welcome.connectionId", "Welcome.epochId"),
            ["sessions"] = sessions,
            ["columnVectors"] = Vectors.Columns(),
            ["keyVectors"] = Vectors.Keys(),
            ["argumentVectors"] = Vectors.Arguments(),
        };
    }

    /// <summary>The corpus as the committed file holds it: indented, LF line endings, trailing newline.</summary>
    public static string Render(JsonObject corpus) =>
        corpus.ToJsonString(new JsonSerializerOptions
        {
            WriteIndented = true,
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        }).ReplaceLineEndings("\n") + "\n";

    private static async Task<JsonObject> HandshakeAndInitialSetAsync(ConformanceServer server, CancellationToken ct)
    {
        await using var session = await RecordingSession.OpenAsync(
            server,
            "handshake-and-initial-set",
            "Hello and Welcome, then every column kind in one initial set: the set spans several chunks, so chunk 0 carries the descriptor and later chunks carry null. Rows 1-4 are SampleRows variants 0-3, so every value here is one the module wrote. A second subscription matches nothing: an empty set still carries its descriptor and its anchor.",
            ct).ConfigureAwait(false);

        for (var variant = 0; variant < 4; variant++)
            await session.CallAsync((uint)(variant + 1), "PutSample", ReducerArgs.Encode((long)(variant + 1), variant, 1), ct).ConfigureAwait(false);

        var set = await session.SubscribeAsync(1, "SELECT * FROM Sample WHERE Group = :g", new Dictionary<string, object?> { ["g"] = 1L }, ct).ConfigureAwait(false);
        CheckSampleRows(set, expectedIds: [1, 2, 3, 4], group: 1);
        await session.SubscribeAsync(2, "SELECT * FROM Sample WHERE Group = :g", new Dictionary<string, object?> { ["g"] = 99L }, ct).ConfigureAwait(false);

        return session.ToJson();
    }

    private static async Task<JsonObject> DeltasAsync(ConformanceServer server, CancellationToken ct)
    {
        await using var session = await RecordingSession.OpenAsync(
            server,
            "deltas",
            "Inserts, updates, and deletes as TransactionUpdate frames. Subscriptions 1 (Group 10-20) and 2 (Group = 20) overlap, so a row in both arrives once per subscription in one frame. Subscription 1 is then re-scoped to 21-30: the diff arrives as a TransactionUpdate at LSN 0, which a client applies without judging it against the anchor. Finally an unsubscribe.",
            ct).ConfigureAwait(false);

        var range = new Dictionary<string, object?> { ["lo"] = 10L, ["hi"] = 20L };
        await session.SubscribeAsync(1, "SELECT * FROM Sample WHERE Group BETWEEN :lo AND :hi", range, ct).ConfigureAwait(false);
        await session.SubscribeAsync(2, "SELECT * FROM Sample WHERE Group = :g", new Dictionary<string, object?> { ["g"] = 20L }, ct).ConfigureAwait(false);

        await session.CallAsync(1, "PutSample", ReducerArgs.Encode(10L, 0, 10), ct, expectDelta: true).ConfigureAwait(false);
        await session.CallAsync(2, "PutSample", ReducerArgs.Encode(20L, 2, 20), ct, expectDelta: true).ConfigureAwait(false);
        await session.CallAsync(3, "ChangeSample", ReducerArgs.Encode(20L, 1), ct, expectDelta: true).ConfigureAwait(false);
        await session.CallAsync(4, "DeleteSample", ReducerArgs.Encode(10L), ct, expectDelta: true).ConfigureAwait(false);
        await session.CallAsync(5, "PutSample", ReducerArgs.Encode(25L, 0, 25), ct).ConfigureAwait(false);

        session.Note("Re-scope subscription 1 to Group 21-30: row 20 leaves, row 25 enters.");
        await session.SendAsync(
            new SubscribeFrame(1, "SELECT * FROM Sample WHERE Group BETWEEN :lo AND :hi", new Dictionary<string, object?> { ["lo"] = 21L, ["hi"] = 30L }) { Channel = MelangeChannels.Data },
            ct).ConfigureAwait(false);
        await session.ReceiveAsync(static frames => frames.Any(static f => f is TransactionUpdateFrame), ct).ConfigureAwait(false);

        session.Note("Unsubscribe 2.");
        await session.SendAsync(new UnsubscribeFrame(2) { Channel = MelangeChannels.Data }, ct).ConfigureAwait(false);
        await session.ReceiveAsync(static frames => frames.Any(static f => f is UnsubscribedFrame), ct).ConfigureAwait(false);
        return session.ToJson();
    }

    private static async Task<JsonObject> CallFailuresAsync(ConformanceServer server, CancellationToken ct)
    {
        await using var session = await RecordingSession.OpenAsync(
            server,
            "call-and-subscribe-failures",
            "A reducer that rejects, an unknown reducer, wrong arguments, and subscriptions the server refuses. Call failures are ReducerResult frames with ok=false; a refused subscription is an Error frame carrying its subscription id.",
            ct).ConfigureAwait(false);

        await session.CallAsync(1, "Refuse", ReducerArgs.Encode("refused by design"), ct).ConfigureAwait(false);
        await session.CallAsync(2, "NoSuchReducer", ReducerArgs.Encode(), ct).ConfigureAwait(false);
        await session.CallAsync(3, "PutSample", ReducerArgs.Encode("not a number"), ct).ConfigureAwait(false);

        session.Note("Subscribe 5 to a table that does not exist.");
        await session.SendAsync(new SubscribeFrame(5, "SELECT * FROM Nope", null) { Channel = MelangeChannels.Data }, ct).ConfigureAwait(false);
        await session.ReceiveAsync(static frames => frames.Any(static f => f is ErrorFrame), ct).ConfigureAwait(false);

        session.Note("Subscribe 6 with text that does not parse.");
        await session.SendAsync(new SubscribeFrame(6, "SELEKT everything", null) { Channel = MelangeChannels.Data }, ct).ConfigureAwait(false);
        await session.ReceiveAsync(static frames => frames.Any(static f => f is ErrorFrame), ct).ConfigureAwait(false);

        session.Note("Subscribe 7 naming a parameter it does not supply.");
        await session.SendAsync(new SubscribeFrame(7, "SELECT * FROM Sample WHERE Group = :g", null) { Channel = MelangeChannels.Data }, ct).ConfigureAwait(false);
        await session.ReceiveAsync(static frames => frames.Any(static f => f is ErrorFrame), ct).ConfigureAwait(false);
        return session.ToJson();
    }

    private static async Task<JsonObject> ColumnMasksAsync(ConformanceServer server, CancellationToken ct)
    {
        await using var session = await RecordingSession.OpenAsync(
            server,
            "column-masks",
            "A column policy hides Secret.Hidden from everyone but the row's owner. The caller's own row arrives with an empty mask (every column present); another identity's row arrives with a mask, and its row bytes simply do not contain the hidden column. Keys here are string-encoded.",
            ct).ConfigureAwait(false);

        await session.CallAsync(1, "PutSecret", ReducerArgs.Encode("mine", ConformanceServer.Caller, 1, "only me"), ct).ConfigureAwait(false);
        await session.CallAsync(2, "PutSecret", ReducerArgs.Encode("theirs", SampleRows.OtherIdentity, 2, "not you"), ct).ConfigureAwait(false);
        await session.SubscribeAsync(1, "SELECT * FROM Secret", null, ct).ConfigureAwait(false);
        await session.CallAsync(3, "PutSecret", ReducerArgs.Encode("later", SampleRows.OtherIdentity, 3, "still not you"), ct, expectDelta: true).ConfigureAwait(false);
        return session.ToJson();
    }

    private static async Task<JsonObject> ProducersAsync(ConformanceServer server, CancellationToken ct)
    {
        await using var session = await RecordingSession.OpenAsync(
            server,
            "producers",
            "Producer calls (protocol 3). The result is one tagged value in the reducer-argument encoding: a record is an Array of its fields in declaration order, a list an Array of its elements. A trailing parameter with a default may be left off.",
            ct).ConfigureAwait(false);

        await session.CallAsync(1, "PutSample", ReducerArgs.Encode(50L, 0, 50), ct).ConfigureAwait(false);
        await session.CallAsync(2, "PutSample", ReducerArgs.Encode(51L, 2, 50), ct).ConfigureAwait(false);
        await session.CallProducerAsync(3, "Summarize", ReducerArgs.Encode(50, "two rows"), ct).ConfigureAwait(false);
        await session.CallProducerAsync(4, "Summarize", ReducerArgs.Encode(98), ct).ConfigureAwait(false);
        await session.CallProducerAsync(5, "NoSuchProducer", ReducerArgs.Encode(), ct).ConfigureAwait(false);
        return session.ToJson();
    }

    private static async Task<JsonObject> HeartbeatAsync(ConformanceServer server, CancellationToken ct)
    {
        await using var session = await RecordingSession.OpenAsync(
            server,
            "heartbeat",
            "The client pings and the server answers with the same id; then the server's heartbeat fires (the run moves the server's clock) and the client must answer the server's Ping with a Pong, or be disconnected after Transport:HeartbeatTimeoutMs.",
            ct).ConfigureAwait(false);

        session.Note("Client sends Ping 7.");
        await session.SendAsync(new PingFrame(7), ct).ConfigureAwait(false);
        await session.ReceiveAsync(static frames => frames.Any(static f => f is PongFrame), ct).ConfigureAwait(false);

        session.Note($"The server's clock moves {ConformanceServer.HeartbeatIntervalMs} ms: its heartbeat sends a Ping.");
        server.Clock.Advance(TimeSpan.FromMilliseconds(ConformanceServer.HeartbeatIntervalMs));
        var ping = await session.ReceiveAsync(static frames => frames.Any(static f => f is PingFrame), ct).ConfigureAwait(false);
        await session.SendAsync(new PongFrame(((PingFrame)ping[0]).Id), ct).ConfigureAwait(false);
        return session.ToJson();
    }

    private static async Task<JsonObject[]> ResumeAsync(ConformanceServer server, CancellationToken ct)
    {
        var query = "SELECT * FROM Sample WHERE Group = :g";
        var parameters = new Dictionary<string, object?> { ["g"] = 40L };

        Guid epoch;
        ulong lastAcked;
        JsonObject before;
        await using (var first = await RecordingSession.OpenAsync(
            server,
            "resume-before-drop",
            "A subscription receives one delta, then the socket drops without a close. The client's resume cursor is the highest LSN it fully applied: the LSN of that TransactionUpdate.",
            ct).ConfigureAwait(false))
        {
            await first.SubscribeAsync(1, query, parameters, ct).ConfigureAwait(false);
            var delta = await first.CallAsync(1, "PutSample", ReducerArgs.Encode(40L, 0, 40), ct, expectDelta: true).ConfigureAwait(false);
            epoch = first.EpochId;
            lastAcked = delta.OfType<TransactionUpdateFrame>().Single().Lsn;
            first.Abort();
            before = first.ToJson();
        }

        JsonObject writer;
        await using (var other = await RecordingSession.OpenAsync(
            server,
            "resume-gap-writer",
            "While the first client is away, another connection commits a row its subscription matches.",
            ct).ConfigureAwait(false))
        {
            await other.CallAsync(1, "PutSample", ReducerArgs.Encode(41L, 2, 40), ct).ConfigureAwait(false);
            writer = other.ToJson();
        }

        JsonObject accepted;
        await using (var resumed = await RecordingSession.OpenAsync(
            server,
            "resume-accepted",
            "The client reconnects and sends Resume with the epoch from its old Welcome, its cursor, and its subscriptions (same ids, queries, parameters). The server accepts and replays the gap as ordinary TransactionUpdate frames; the client keeps the descriptor it already held, so no initial set and no descriptor arrive. The subscription then carries on live.",
            ct).ConfigureAwait(false))
        {
            // The gap's rows decode against the descriptor the client already holds from before the
            // drop; a decoder replaying this session takes it from "resume-before-drop".
            resumed.AdoptDescriptor(1, before);
            resumed.Note("Resume against the original epoch from the cursor; subscription 1 as before. Rows decode against the descriptor held from session resume-before-drop.");
            await resumed.SendAsync(new ResumeFrame(epoch, lastAcked, [new ResumeSubscription(1, query, parameters)]), ct).ConfigureAwait(false);
            await resumed.ReceiveAsync(
                static frames => frames.Any(static f => f is ResumeResultFrame) && frames.Any(static f => f is TransactionUpdateFrame),
                ct).ConfigureAwait(false);
            await resumed.CallAsync(1, "PutSample", ReducerArgs.Encode(42L, 0, 40), ct, expectDelta: true).ConfigureAwait(false);
            accepted = resumed.ToJson();
        }

        JsonObject rejected;
        await using (var stale = await RecordingSession.OpenAsync(
            server,
            "resume-rejected",
            "A Resume against an epoch this server's log is not: rejected. The client must discard every cached row and re-establish each subscription with an ordinary Subscribe, which answers with a full initial set.",
            ct).ConfigureAwait(false))
        {
            stale.Note("Resume against an epoch the server never had.");
            await stale.SendAsync(new ResumeFrame(Guid.Parse("11111111-2222-3333-4444-555555555555"), lastAcked, [new ResumeSubscription(1, query, parameters)]), ct).ConfigureAwait(false);
            await stale.ReceiveAsync(static frames => frames.Any(static f => f is ResumeResultFrame), ct).ConfigureAwait(false);
            await stale.SubscribeAsync(1, query, parameters, ct).ConfigureAwait(false);
            rejected = stale.ToJson();
        }

        return [before, writer, accepted, rejected];
    }

    private static async Task<JsonObject> ReauthenticateAsync(ConformanceServer server, CancellationToken ct)
    {
        await using var session = await RecordingSession.OpenAsync(
            server,
            "reauthenticate",
            "A fresh token for the same identity is accepted. A token for a different identity is not a refresh: the server sends identity_changed and closes the connection.",
            ct).ConfigureAwait(false);

        session.Note("Reauthenticate with a fresh token for the same subject.");
        await session.SendAsync(new ReauthenticateFrame(server.Token), ct).ConfigureAwait(false);
        await session.ReceiveAsync(static frames => frames.Any(static f => f is ReauthenticateResultFrame), ct).ConfigureAwait(false);

        session.Note("Reauthenticate with a token for a different subject.");
        await session.SendAsync(new ReauthenticateFrame(server.TokenFor("someone-else")), ct).ConfigureAwait(false);
        await session.ReceiveUntilClosedAsync(ct).ConfigureAwait(false);
        return session.ToJson();
    }

    /// <summary>
    /// The recorder's own check: the server-encoded rows decode to exactly the values the module
    /// wrote. Without it the corpus would only prove the C# decoder agrees with itself.
    /// </summary>
    private static void CheckSampleRows(IReadOnlyList<Frame> frames, long[] expectedIds, int group)
    {
        var chunks = frames.OfType<SubscriptionAppliedFrame>().ToList();
        var descriptor = chunks[0].Descriptor ?? throw new InvalidOperationException("Chunk 0 carried no descriptor.");
        if (chunks.Count < 2)
            throw new InvalidOperationException($"The every-kind initial set fit one chunk; lower {nameof(ConformanceServer.InitialSetChunkBytes)} so the corpus covers chunking.");
        if (chunks.Skip(1).Any(static chunk => chunk.Descriptor is not null))
            throw new InvalidOperationException("A chunk after chunk 0 carried a descriptor.");

        var rows = chunks.SelectMany(static chunk => chunk.Rows).ToList();
        var ids = rows.Select(static row => BitConverter.ToInt64(row.Row.Span[..8])).Order().ToArray();
        if (!ids.SequenceEqual(expectedIds))
            throw new InvalidOperationException($"Initial set held ids [{string.Join(", ", ids)}], expected [{string.Join(", ", expectedIds)}].");

        foreach (var row in rows)
        {
            var id = BitConverter.ToInt64(row.Row.Span[..8]);
            var decoded = CorpusJson.Row(row.Key, row.Row.Span, row.ColumnMask.Span, descriptor)["columns"]!;
            var expected = Harness.Truth.Sample(id, (int)id - 1, group);
            if (!JsonNode.DeepEquals(decoded, expected))
                throw new InvalidOperationException($"Sample {id} decoded as {decoded.ToJsonString()}, but the module wrote {expected.ToJsonString()}.");
        }
    }


    /// <summary>One recorded connection: raw socket, the frames it received, and the steps that caused them.</summary>
    private sealed class RecordingSession : IAsyncDisposable
    {
        private readonly ClientWebSocket _socket;
        private readonly string _name;
        private readonly string _description;
        private readonly JsonArray _steps = [];
        private readonly Dictionary<uint, WireDescriptor> _descriptors = [];
        private readonly byte[] _buffer = new byte[1 << 20];
        private string? _note;
        private string? _descriptorsFrom;

        private RecordingSession(ClientWebSocket socket, string name, string description)
        {
            _socket = socket;
            _name = name;
            _description = description;
        }

        public Guid EpochId { get; private set; }

        public static async Task<RecordingSession> OpenAsync(ConformanceServer server, string name, string description, CancellationToken ct)
        {
            var socket = new ClientWebSocket();
            await socket.ConnectAsync(server.SocketUri, ct).ConfigureAwait(false);
            var session = new RecordingSession(socket, name, description);
            session.Note($"Hello offering protocol versions {MessagePackFrameSerializer.MinProtocolVersion}-{MessagePackFrameSerializer.ProtocolVersion} with a bearer token.");
            await session.SendAsync(new HelloFrame(MessagePackFrameSerializer.MinProtocolVersion, MessagePackFrameSerializer.ProtocolVersion, server.Token), ct).ConfigureAwait(false);
            var welcome = await session.ReceiveAsync(static frames => frames.Any(static f => f is WelcomeFrame), ct).ConfigureAwait(false);
            session.EpochId = ((WelcomeFrame)welcome[0]).EpochId;
            return session;
        }

        /// <summary>Describes the next step; recorded with the frames it receives.</summary>
        public void Note(string note) => _note = note;

        public async Task SendAsync(Frame frame, CancellationToken ct) =>
            await _socket.SendAsync(Serializer.Serialize(frame), WebSocketMessageType.Binary, endOfMessage: true, ct).ConfigureAwait(false);

        public async Task<IReadOnlyList<Frame>> SubscribeAsync(uint id, string query, Dictionary<string, object?>? parameters, CancellationToken ct)
        {
            var rendered = parameters is null ? "no parameters" : string.Join(", ", parameters.Select(static p => $":{p.Key} = {p.Value}"));
            Note($"Subscribe {id}: {query} ({rendered}).");
            await SendAsync(new SubscribeFrame(id, query, parameters) { Channel = MelangeChannels.Data }, ct).ConfigureAwait(false);
            return await ReceiveAsync(frames => frames.Any(f => f is SubscriptionAppliedFrame { IsLast: true } s && s.SubscriptionId == id), ct).ConfigureAwait(false);
        }

        public async Task<IReadOnlyList<Frame>> CallAsync(uint requestId, string reducer, byte[] arguments, CancellationToken ct, bool expectDelta = false)
        {
            Note($"CallReducer {requestId}: {reducer}({string.Join(", ", CorpusJson.Arguments(arguments).Select(static a => a!.ToJsonString()))}).");
            await SendAsync(new CallReducerFrame(requestId, reducer, arguments, null) { Channel = MelangeChannels.Calls }, ct).ConfigureAwait(false);
            return await ReceiveAsync(
                frames => frames.Any(f => f is ReducerResultFrame r && r.RequestId == requestId)
                    && (!expectDelta || frames.Any(static f => f is TransactionUpdateFrame)),
                ct).ConfigureAwait(false);
        }

        public async Task CallProducerAsync(uint requestId, string producer, byte[] arguments, CancellationToken ct)
        {
            Note($"CallProducer {requestId}: {producer}({string.Join(", ", CorpusJson.Arguments(arguments).Select(static a => a!.ToJsonString()))}).");
            await SendAsync(new CallProducerFrame(requestId, producer, arguments, null) { Channel = MelangeChannels.Calls }, ct).ConfigureAwait(false);
            await ReceiveAsync(frames => frames.Any(f => f is ProducerResultFrame p && p.RequestId == requestId), ct).ConfigureAwait(false);
        }

        /// <summary>
        /// Reads frames until <paramref name="done"/> holds, then records them as one step,
        /// stably ordered by channel: frames on different channels have no promised order, so
        /// recording arrival order would make the corpus flap.
        /// </summary>
        public async Task<IReadOnlyList<Frame>> ReceiveAsync(Func<IReadOnlyList<Frame>, bool> done, CancellationToken ct)
        {
            var received = new List<(Frame Frame, byte[] Bytes)>();
            using var timeout = CancellationTokenSource.CreateLinkedTokenSource(ct);
            timeout.CancelAfter(StepTimeout);
            while (!done([.. received.Select(static r => r.Frame)]))
            {
                byte[]? bytes;
                try
                {
                    bytes = await ReceiveOneAsync(timeout.Token).ConfigureAwait(false);
                }
                catch (OperationCanceledException) when (!ct.IsCancellationRequested)
                {
                    throw new TimeoutException(
                        $"Session '{_name}', step '{_note}': timed out after {StepTimeout.TotalSeconds}s having received " +
                        $"[{string.Join(", ", received.Select(static r => r.Frame.ToString()))}].");
                }

                if (bytes is null)
                    throw new InvalidOperationException($"Session '{_name}': the server closed the socket during step '{_note}'.");
                received.Add((Serializer.Deserialize(bytes), bytes));
            }

            Record(received);
            return [.. received.OrderBy(static r => r.Frame.Channel).Select(static r => r.Frame)];
        }

        /// <summary>Reads until the server closes the socket, recording everything it sent first.</summary>
        public async Task ReceiveUntilClosedAsync(CancellationToken ct)
        {
            var received = new List<(Frame Frame, byte[] Bytes)>();
            using var timeout = CancellationTokenSource.CreateLinkedTokenSource(ct);
            timeout.CancelAfter(StepTimeout);
            while (await ReceiveOneAsync(timeout.Token).ConfigureAwait(false) is { } bytes)
                received.Add((Serializer.Deserialize(bytes), bytes));
            Record(received);
        }

        /// <summary>Takes over the descriptor a previous session held for a resumed subscription.</summary>
        public void AdoptDescriptor(uint subscriptionId, JsonObject previous)
        {
            _descriptorsFrom = (string)previous["name"]!;
            foreach (var step in previous["steps"]!.AsArray())
            {
                foreach (var frame in step!["receive"]!.AsArray())
                {
                    if (frame!["expect"]!["descriptor"] is JsonObject descriptor && (uint)frame["expect"]!["subscriptionId"]! == subscriptionId)
                    {
                        _descriptors[subscriptionId] = new WireDescriptor(
                            (string)descriptor["table"]!,
                            [.. descriptor["columns"]!.AsArray().Select(static c => new WireColumn((string)c!["name"]!, (ColumnKind)(int)c["kind"]!))]);
                    }
                }
            }
        }

        public void Abort() => _socket.Abort();

        public JsonObject ToJson() => new()
        {
            ["name"] = _name,
            ["description"] = _description,
            ["descriptorsFrom"] = _descriptorsFrom,
            ["steps"] = _steps.DeepClone(),
        };

        public ValueTask DisposeAsync()
        {
            _socket.Dispose();
            return ValueTask.CompletedTask;
        }

        private void Record(List<(Frame Frame, byte[] Bytes)> received)
        {
            var frames = new JsonArray();
            foreach (var (frame, bytes) in received.OrderBy(static r => r.Frame.Channel))
            {
                var (recorded, wire) = frame is WelcomeFrame welcome ? Normalize(welcome) : (frame, bytes);
                frames.Add(new JsonObject
                {
                    ["hex"] = CorpusJson.Hex(wire),
                    ["expect"] = CorpusJson.Frame(recorded, _descriptors),
                });
            }

            _steps.Add(new JsonObject { ["send"] = _note, ["receive"] = frames });
            _note = null;
        }

        private static (Frame Frame, byte[] Bytes) Normalize(WelcomeFrame welcome)
        {
            var fixedWelcome = welcome with { ConnectionId = FixedConnectionId, EpochId = FixedEpochId };
            return (fixedWelcome, Serializer.Serialize(fixedWelcome));
        }

        private async Task<byte[]?> ReceiveOneAsync(CancellationToken ct)
        {
            var length = 0;
            while (true)
            {
                var result = await _socket.ReceiveAsync(_buffer.AsMemory(length), ct).ConfigureAwait(false);
                if (result.MessageType == WebSocketMessageType.Close)
                    return null;
                length += result.Count;
                if (result.EndOfMessage)
                    return _buffer.AsSpan(0, length).ToArray();
            }
        }
    }
